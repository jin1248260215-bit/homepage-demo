def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", default="results_baseline.json")
    a = ap.parse_args()
    path = os.path.join(EVAL_DIR, a.file)
    if not os.path.exists(path):
        raise SystemExit(f"找不到 {path}")

    js = json.load(open(path, encoding="utf-8"))
    gold = json.load(open(os.path.join(EVAL_DIR, "gold_answers.json"), encoding="utf-8"))

    for it in js["items"]:
        qid = it["qid"]
        if qid in GRADES:
            verdict, err, note = GRADES[qid]
            it["verdict"] = verdict
            it["error_class"] = err
            it["note"] = note
        g = gold.get(str(qid))
        if g:
            it["gold_answer"] = g["answer"]
            it["gold_source"] = g.get("source")

    js["summary"] = summarize(js["items"])
    js["graded_by"] = "人工读年报原文逐题判定（见 eval/apply_grades.py 中的依据）"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(js, f, ensure_ascii=False, indent=1)

    s = js["summary"]
    print(f"{path}\n")
    print(f"对 {s['n_correct']} / 部分对 {s['n_partial']} / 错 {s['n_wrong']}"
          f"  （证据召回率 {s['recall_rate']}%，平均检索 {s['avg_ms']} ms）")
    print(f"错因分布：{s['error_class_counts']}")
    print("\n按题型：")
    for t, v in s["by_type"].items():
        print(f"  {t}: 对 {v['correct']} / 部分 {v['partial']} / 错 {v['wrong']}  (召回率 {v['recall_rate']}%)")


if __name__ == "__main__":
    main()
